"""Generator for the 8x16 font ROM (rtl/font_rom.v).

Only 64 characters, ASCII 0x20 (space) ~ 0x5F ('_'), are included (digits, upper-case letters, symbols). 64 x 16 = 1024 bytes.
A 5x7 glyph is placed in the middle of an 8x16 cell and stretched 2x vertically.
  - cell width : 1 blank pixel on the left, 5 glyph pixels, 2 blank pixels on the right
  - cell height: 1 blank row on top, 7 glyph rows x 2 = 14 rows, 1 blank row at the bottom
Usage:  python scripts/gen_font.py
"""
import os

G = {}

def glyph(ch, rows):
    assert len(rows) == 7 and all(len(r) == 5 for r in rows), ch
    G[ch] = rows

