def cell(ch):
    """16 rows of an 8x16 cell (8 bits each, bit7 = leftmost pixel)"""
    rows = G.get(ch, G[' '])
    out = [0]                                   # top row blank
    for r in rows:
        v = 0
        for i, c in enumerate(r):               # 1 blank pixel on the left -> glyph is bit6..bit2
            if c == '#':
                v |= 1 << (6 - i)
        out += [v, v]
    out.append(0)                               # bottom row blank
    assert len(out) == 16
    return out


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    dst = os.path.join(here, "..", "rtl", "font_rom.v")
    lines = []
    lines.append("`timescale 1ns / 1ps")
    lines.append("//------------------------------------------------------------------------------")
    lines.append("// font_rom : 8x16 font, ASCII 0x20 ~ 0x5F (digits, upper-case letters, symbols), 64 characters")
    lines.append("//   Generated by scripts/gen_font.py. Do not edit by hand; edit the script instead.")
    lines.append("//   bits[7] is the leftmost pixel of the character cell. Characters out of range are blank.")
    lines.append("//------------------------------------------------------------------------------")
    lines.append("module font_rom (")
    lines.append("    input  wire [7:0] ascii,")
    lines.append("    input  wire [3:0] row,")
    lines.append("    output reg  [7:0] bits")
    lines.append(");")
    lines.append("    wire       in_rng = (ascii >= 8'h20) && (ascii <= 8'h5F);")
    lines.append("    wire [5:0] code   = ascii[5:0] - 6'h20;")
    lines.append("    always @* begin")
    lines.append("        bits = 8'h00;")
    lines.append("        if (in_rng) begin")
    lines.append("            case ({code, row})")
    for code in range(64):
        ch = chr(0x20 + code)
        data = cell(ch)
        if all(b == 0 for b in data):
            continue
        for r, b in enumerate(data):
            if b:
                lines.append("                10'd%d: bits = 8'h%02X;  // '%s' row %d"
                             % (code * 16 + r, b, ch if ch != '\\' else 'backslash', r))
    lines.append("                default: bits = 8'h00;")
    lines.append("            endcase")
    lines.append("        end")
    lines.append("    end")
    lines.append("endmodule")
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", os.path.normpath(dst))


if __name__ == "__main__":
    main()
