import math

W, H = 32, 40

def blank():
    return [[0] * W for _ in range(H)]

def plot(g, x, y):
    xi, yi = int(round(x)), int(round(y))
    if 0 <= xi < W and 0 <= yi < H:
        g[yi][xi] = 1

def line(g, x0, y0, x1, y1):
    n = 400
    for i in range(n + 1):
        t = i / n
        plot(g, x0 + (x1 - x0) * t, y0 + (y1 - y0) * t)

def and_gate():
    g = blank()
    line(g, 0, 0, 15, 0)
    line(g, 0, 39, 15, 39)
    line(g, 0, 0, 0, 39)
    n = 800
    for i in range(n + 1):
        t = -math.pi / 2 + math.pi * i / n
        plot(g, 15 + 16 * math.cos(t), 19.5 + 19.5 * math.sin(t))
    return g

def or_curves(g, xoff, xscale):
    n = 800
    for i in range(n + 1):
        th = (math.pi / 2) * i / n
        x = xoff + xscale * 31 * math.sin(th)
        y = 19.5 * (1 - math.cos(th))
        plot(g, x, y)
        plot(g, x, 39 - y)

def left_arc(g, xoff):
    n = 800
    for i in range(n + 1):
        u = -1 + 2 * i / n
        plot(g, xoff + 8 * math.sqrt(max(0.0, 1 - u * u)), 19.5 + 19.5 * u)

def or_gate():
    g = blank()
    or_curves(g, 0, 1.0)
    left_arc(g, 0)
    return g

def xor_gate():
    g = blank()
    or_curves(g, 4, 27 / 31)
    left_arc(g, 4)
    left_arc(g, 0)
    return g

def leftmost(g, row):
    for x in range(W):
        if g[row][x]:
            return x
    return 0

gates = [and_gate(), or_gate(), xor_gate()]
names = ["AND", "OR", "XOR"]

for n, g in zip(names, gates):
    print(n)
    for r in g:
        print(''.join('#' if v else '.' for v in r))

out = []
out.append("`timescale 1ns / 1ps")
out.append("//------------------------------------------------------------------------------")
out.append("// gate_sprite : 32 x 40 outline bitmaps of the AND / OR / XOR gate symbols (generated by")
out.append("//   scripts/gen_sprite.py, do not edit by hand). bits[31-col] is the pixel at column col.")
out.append("//   kind : 0 AND, 1 OR, 2 XOR.  lead_a / lead_b : first symbol column on the rows of the")
out.append("//   two input wires (rows 8 and 32), so the input wires can be drawn up to the symbol.")
out.append("//------------------------------------------------------------------------------")
out.append("module gate_sprite (")
out.append("    input  wire [1:0]  kind,")
out.append("    input  wire [5:0]  row,")
out.append("    output reg  [31:0] bits,")
out.append("    output reg  [4:0]  lead_a,")
out.append("    output reg  [4:0]  lead_b")
out.append(");")
out.append("    always @* begin")
out.append("        bits = 32'd0;")
out.append("        case (kind)")
for k, g in enumerate(gates):
    out.append("            2'd%d: begin" % k)
    out.append("                case (row)")
    for r in range(H):
        v = 0
        for c in range(W):
            if g[r][c]:
                v |= 1 << (31 - c)
        out.append("                    6'd%d: bits = 32'h%08X;" % (r, v))
    out.append("                    default: bits = 32'd0;")
    out.append("                endcase")
    out.append("            end")
out.append("            default: bits = 32'd0;")
out.append("        endcase")
out.append("    end")
out.append("    always @* begin")
out.append("        case (kind)")
for k, g in enumerate(gates):
    out.append("            2'd%d: begin lead_a = 5'd%d; lead_b = 5'd%d; end" % (k, leftmost(g, 8), leftmost(g, 32)))
out.append("            default: begin lead_a = 5'd0; lead_b = 5'd0; end")
out.append("        endcase")
out.append("    end")
out.append("endmodule")
open(r"E:\Vivado\project_jiwoo_v2\rtl\gate_sprite.v", "w").write("\n".join(out) + "\n")
